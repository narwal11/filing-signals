"""db.py row mapping. No database and no network: only record -> rows is tested here.
The live load is checked by scripts/check_db.py."""

import hashlib
import re
from datetime import date, datetime, timezone

import db


def make_record(form="10-K", sections=None, items=(), item_keys_found=(), raw="2021-01-27T21:30:35.000Z"):
    filing = {
        "cik": 320193, "ticker": "AAPL", "company": "Apple Inc.",
        "accession": "0000320193-21-000009", "form": form,
        "filed_date": "2021-01-27", "accepted_at": "2021-01-27T21:30:35+00:00",
        "report_date": "2020-12-26", "items": list(items),
        "primary_document": "aapl-20210127.htm", "primary_url": "https://example/x.htm",
    }
    if raw is not None:
        filing["accepted_at_raw"] = raw
    return {"filing": filing, "sections": sections or [], "item_keys_found": list(item_keys_found)}


def section(key, text, source="primary"):
    return {"key": key, "title": key, "text": text, "source": source, "heading": f"Item {key}", "char_count": len(text)}


def test_filing_row_converts_types():
    rows = db.record_to_rows(make_record(sections=[section("1A", "x" * 9000), section("7", "y" * 9000)]))
    filing = rows["filing"]
    assert rows["company"] == (320193, "Apple Inc.")
    assert rows["ticker"] == (320193, "AAPL")
    assert filing["filed_date"] == date(2021, 1, 27)
    assert filing["report_date"] == date(2020, 12, 26)
    assert filing["accepted_at"] == datetime(2021, 1, 27, 21, 30, 35, tzinfo=timezone.utc)
    assert filing["accepted_at_raw"] == "2021-01-27T21:30:35.000Z"
    assert filing["layout"] == "standard"
    assert filing["sec_metadata_mismatch"] is False


def test_rows_have_exactly_the_columns_the_upserts_use():
    rows = db.record_to_rows(make_record(sections=[section("1A", "x" * 9000)]))
    # The SQL is written out by hand, so check its %(name)s placeholders match the row dicts.
    assert set(re.findall(r"%\((\w+)\)s", db.UPSERT_FILING)) == set(db.FILING_COLUMNS) == set(rows["filing"])
    assert set(re.findall(r"%\((\w+)\)s", db.UPSERT_SECTION)) == set(db.SECTION_COLUMNS) == set(rows["sections"][0])


def test_record_without_raw_timestamp_maps_to_none():
    assert db.record_to_rows(make_record(raw=None))["filing"]["accepted_at_raw"] is None


def test_section_rows_hash_the_text_and_leave_char_count_to_postgres():
    rows = db.record_to_rows(make_record(sections=[section("1A", "x" * 9000), section("7", "y" * 9000)]))
    assert [s["key"] for s in rows["sections"]] == ["1A", "7"]
    for s in rows["sections"]:
        assert set(s) == set(db.SECTION_COLUMNS)
        assert "char_count" not in s  # generated by Postgres
        assert s["text_sha256"] == hashlib.sha256(s["text"].encode("utf-8")).digest()
        assert s["accession"] == "0000320193-21-000009"
        assert s["pointer_kind"] is None


def test_cross_reference_filing_is_non_standard_and_marks_only_the_pointer_section():
    pointer = "Management's discussion and analysis appears on pages 46-160."
    rows = db.record_to_rows(make_record(sections=[section("1A", "x" * 9000), section("7", pointer)]))
    assert rows["filing"]["layout"] == "non_standard"
    kinds = {s["key"]: s["pointer_kind"] for s in rows["sections"]}
    assert kinds == {"1A": None, "7": "page"}


def test_earnings_8k_without_2_02_heading_sets_mismatch_flag():
    record = make_record(
        form="8-K", items=["2.02", "9.01"], item_keys_found=["2.01", "9.01"],
        sections=[section("EX-99.1", "z" * 2000, source="EX-99.1")],
    )
    rows = db.record_to_rows(record)
    assert rows["filing"]["sec_metadata_mismatch"] is True
    assert rows["filing"]["sec_items"] == ["2.02", "9.01"]
    assert rows["filing"]["items_found"] == ["2.01", "9.01"]


def test_upserts_skip_unchanged_rows():
    # Reloading the same file must not rewrite rows (that would leave dead copies of the text).
    assert "IS DISTINCT FROM" in db.UPSERT_FILING
    assert "IS DISTINCT FROM" in db.UPSERT_SECTION
    assert "IS DISTINCT FROM" in db.UPSERT_COMPANY
